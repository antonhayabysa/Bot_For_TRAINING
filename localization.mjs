export function getTranslation(key, language, params = {}) {
  if (!translations[key] || !translations[key][language]) {
    console.error(
      `Translation for key "${key}" in language "${language}" not found.`
    );
    return "";
  }

  if (params.date && params.date instanceof Date) {
    const locale =
      language === "ru" ? "ru-RU" : language === "uk" ? "uk-UA" : "en-US";
    params.date = params.date.toLocaleDateString(locale, {
      day: "numeric",
      month: "long",
      year: "numeric",
    });
  }
  let translation = translations[key][language];
  Object.keys(params).forEach((param) => {
    if (params[param] !== undefined) {
      translation = translation.replace(`{${param}}`, params[param]);
    }
  });
  return translation;
}
